function date_th(data_date_th) {
    var date = data_date_th;
    var dateObj = new Date(date);
    // การตั้งค่าชื่อเดือนในภาษาไทย
    var thaiMonths = [
        "มกราคม", "กุมภาพันธ์", "มีนาคม", "เมษายน", "พฤษภาคม", "มิถุนายน",
        "กรกฎาคม", "สิงหาคม", "กันยายน", "ตุลาคม", "พฤศจิกายน", "ธันวาคม"
    ];
    // การตั้งค่าวัน
    var day = dateObj.getDate();
    // การตั้งค่าเดือน
    var month = thaiMonths[dateObj.getMonth()];
    // การตั้งค่าปี โดยเพิ่ม 543 เพื่อแปลงเป็นปี พ.ศ.
    var year = dateObj.getFullYear() + 543;
    var thaiDate = day + ' ' + month + ' ' + year;
    return thaiDate;

    //console.log(thaiDate); // ผลลัพธ์: 7 มิถุนายน 2567
};
