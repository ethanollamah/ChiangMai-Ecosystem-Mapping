function moral_sty(score) {
    var result = '';
    if (score >= 0 && score <= 49) {
        result = 'ปรับปรุง';
    } else if (score >= 50 && score <= 69) {
        result = 'พอใช้';
    } else if (score >= 70 && score <= 89) {
        result = 'ดี';
    } else if (score >= 90) {
        result = 'ดีมาก';
    }
    return result;
};

