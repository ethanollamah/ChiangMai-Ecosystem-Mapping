function percen(num_1, num_2) {
    // แปลงค่าเป็นตัวเลข
    var num_t = parseInt(num_1); // จำนวนรวม
    var num_p = parseInt(num_2); // จำนวนย่อย

    // ตรวจสอบค่าจำนวนรวมไม่ให้เป็นศูนย์
    if (num_t === 0) {
        return '0%'; // กรณีหารด้วยศูนย์
    }

    // คำนวณเปอร์เซ็นต์
    var percentage = ((num_p / num_t) * 100).toFixed(3);
    return '( ' + percentage + '% )';
};

